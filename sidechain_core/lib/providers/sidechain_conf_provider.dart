import 'package:get_it/get_it.dart';
import 'package:sidechain_core/sidechain_core.dart';

/// The conf file of one sidechain: `<registryKey>.conf` in the chain datadir.
class SidechainConfProvider extends GenericSidechainConfProvider {
  final Sidechain chain;
  @override
  final String appName;
  final String Function() dataDir;
  final Map<String, String> Function(String network) networkPorts;
  final String Function(String network) defaultConf;
  @override
  final List<String> skippedCliKeys;

  SidechainConfProvider({
    required this.chain,
    required this.appName,
    required this.dataDir,
    required this.networkPorts,
    required this.defaultConf,
    required this.skippedCliKeys,
  });

  /// The orchestrator owns the file, so the app reads and writes it over RPC.
  static Future<GenericSidechainConfProvider> backed(SidechainConfProvider source) {
    return BackendSidechainConfProvider.fromProvider(source, sidechainName: source.chain.registryKey);
  }

  @override
  String get configFileName => '${chain.registryKey}.conf';

  @override
  String getDataDir() => dataDir();

  @override
  Map<String, String> getNetworkPorts(String network) => networkPorts(network);

  @override
  String getDefaultConfig() {
    String network = 'signet';
    try {
      final bitcoinConfProvider = GetIt.I.get<BitcoinConfProvider>();
      network = switch (bitcoinConfProvider.network) {
        BitcoinNetwork.BITCOIN_NETWORK_SIGNET => 'signet',
        BitcoinNetwork.BITCOIN_NETWORK_REGTEST => 'regtest',
        BitcoinNetwork.BITCOIN_NETWORK_ECASH => 'mainnet',
        _ => 'signet',
      };
    } catch (_) {}

    return defaultConf(network);
  }
}

/// The default conf of a sidechain that takes `rpc-addr`, `net-addr` and `mainchain-grpc-url`.
String standardSidechainConf(String displayName, String network, Map<String, String> ports) {
  return '''# $displayName Configuration - Generated by $displayName App
# These settings are converted to CLI arguments when $displayName starts.

# Run in headless mode (no GUI)
headless=true

# Log level for console output
log-level=DEBUG

# Log level for file output
log-level-file=WARN

# Network (signet or regtest)
network=$network

# RPC server address
rpc-addr=${ports['rpc-addr']}

# P2P networking address
net-addr=${ports['net-addr']}

# Mainchain (Enforcer) gRPC connection URL
mainchain-grpc-url=${ports['mainchain-grpc-url']}
''';
}
