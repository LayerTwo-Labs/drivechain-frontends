import 'dart:io';

import 'package:truthcoin/truthcoin_module.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:get_it/get_it.dart';
import 'package:logger/logger.dart';
import 'package:path/path.dart' as path;
import 'package:sail_ui/sail_ui.dart';
import 'package:sail_ui/shell/shell.dart';

const _oldDefaultConf = '''# Truthcoin Configuration - Generated by Truthcoin App
# These settings are converted to CLI arguments when Truthcoin starts.

# Run in headless mode (no GUI)
headless=true

# Log level for console output
log-level=DEBUG

# Log level for file output
log-level-file=WARN

# Network (signet or regtest)
network=signet

# RPC server address
rpc-addr=127.0.0.1:6013

# P2P networking address
net-addr=0.0.0.0:4013

# Mainchain (Enforcer) gRPC connection URL
mainchain-grpc-url=http://localhost:50051
''';

SidechainConfProvider _inDir(String dir, SidechainConfProvider source) => SidechainConfProvider(
  chain: source.chain,
  appName: source.appName,
  dataDir: () => dir,
  networkPorts: source.networkPorts,
  defaultConf: source.defaultConf,
  skippedCliKeys: source.skippedCliKeys,
);

void main() {
  late Directory dir;
  late SidechainConfProvider source;

  setUp(() async {
    GetIt.I.registerSingleton<Logger>(Logger(level: Level.off));
    source = sidechainConfProvider(TruthcoinModule());
    dir = await Directory.systemTemp.createTemp('truthcoin-conf-');
  });

  tearDown(() async {
    await GetIt.I.reset();
    await dir.delete(recursive: true);
  });

  test('the conf provider keeps the name and the default of truthcoin.conf', () {
    expect(source.chain.registryKey, 'truthcoin');
    expect(source.appName, 'Truthcoin');
    expect(source.configFileName, 'truthcoin.conf');
    expect(source.skippedCliKeys, ['network']);
    expect(source.getDefaultConfig(), _oldDefaultConf);
    expect(source.getNetworkPorts('regtest'), {
      'rpc-addr': '127.0.0.1:16013',
      'net-addr': '0.0.0.0:14013',
      'mainchain-grpc-url': 'http://localhost:50051',
    });
    expect(source.getNetworkPorts('mainnet'), {
      'rpc-addr': '127.0.0.1:26013',
      'net-addr': '0.0.0.0:24013',
      'mainchain-grpc-url': 'http://localhost:50051',
    });
  });

  test('the conf provider reads, writes and reads back a truthcoin.conf of the old shape', () async {
    final file = File(path.join(dir.path, 'truthcoin.conf'));
    await file.writeAsString(_oldDefaultConf.replaceFirst('net-addr=0.0.0.0:4013', 'net-addr=0.0.0.0:7777'));

    final provider = _inDir(dir.path, source);
    await provider.loadConfig();
    expect(provider.currentConfig!.getSetting('net-addr'), '0.0.0.0:7777');
    expect(provider.getCliArgs(), contains('--net-addr=0.0.0.0:7777'));

    final changed = provider.getCurrentConfigContent().replaceFirst('log-level=DEBUG', 'log-level=INFO');
    await provider.writeConfig(changed);
    expect(await file.readAsString(), changed);

    final reread = _inDir(dir.path, source);
    await reread.loadConfig();
    expect(reread.currentConfig!.getSetting('log-level'), 'INFO');
    expect(reread.currentConfig!.getSetting('net-addr'), '0.0.0.0:7777');
  });
}
