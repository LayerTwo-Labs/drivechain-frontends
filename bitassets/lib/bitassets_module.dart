import 'dart:io';

import 'package:auto_route/auto_route.dart';
import 'package:bitassets/gen/version.dart';
import 'package:bitassets/providers/asset_analytics_provider.dart';
import 'package:bitassets/providers/bitassets_provider.dart';
import 'package:bitassets/providers/favorites_provider.dart';
import 'package:bitassets/providers/price_alert_provider.dart';
import 'package:bitassets/routing/router.dart';
import 'package:bitassets/widgets/homepage_widget_catalog.dart';
import 'package:get_it/get_it.dart';
import 'package:logger/logger.dart';
import 'package:sail_ui/sail_ui.dart';
import 'package:sail_ui/shell/shell.dart';

class BitAssetsModule extends SidechainModule {
  @override
  Sidechain get chain => BitAssets();

  @override
  String get appName => 'BitAssets';

  @override
  SidechainAppVersion get version => const SidechainAppVersion(
    version: AppVersion.version,
    versionString: AppVersion.versionString,
    buildDate: AppVersion.buildDate,
    commitFull: AppVersion.commitFull,
    appName: AppVersion.appName,
  );

  @override
  RootStackRouter registerRouter(GetIt getIt) {
    if (!getIt.isRegistered<AppRouter>()) {
      getIt.registerSingleton<AppRouter>(AppRouter());
    }
    return getIt.get<AppRouter>();
  }

  @override
  SidechainRPC registerRPC(GetIt getIt) {
    if (!getIt.isRegistered<BitAssetsRPC>()) {
      getIt.registerSingleton<BitAssetsRPC>(BitAssetsLive());
    }
    return getIt.get<BitAssetsRPC>();
  }

  @override
  Future<void> registerChainProviders(GetIt getIt, Directory applicationDir, Logger log) async {
    if (!getIt.isRegistered<BitAssetsProvider>()) {
      getIt.registerLazySingleton<BitAssetsProvider>(
        () => BitAssetsProvider(),
        dispose: (provider) => provider.dispose(),
      );
    }
    if (!getIt.isRegistered<AssetAnalyticsProvider>()) {
      getIt.registerLazySingleton<AssetAnalyticsProvider>(
        () => AssetAnalyticsProvider(),
        dispose: (provider) => provider.dispose(),
      );
    }
    if (!getIt.isRegistered<FavoritesProvider>()) {
      getIt.registerLazySingleton<FavoritesProvider>(
        () => FavoritesProvider(),
        dispose: (provider) => provider.dispose(),
      );
    }
    if (!getIt.isRegistered<PriceAlertProvider>()) {
      getIt.registerLazySingleton<PriceAlertProvider>(
        () => PriceAlertProvider(),
        dispose: (provider) => provider.dispose(),
      );
    }
  }

  @override
  Map<String, String> confPorts(String network) {
    switch (network) {
      case 'regtest':
        return {
          'rpc-host': '127.0.0.1',
          'rpc-port': '16004',
          'net-addr': '0.0.0.0:14004',
          'zmq-addr': '127.0.0.1:38004',
          'mainchain-grpc-port': '50051',
        };
      case 'mainnet':
        return {
          'rpc-host': '127.0.0.1',
          'rpc-port': '26004',
          'net-addr': '0.0.0.0:24004',
          'zmq-addr': '127.0.0.1:48004',
          'mainchain-grpc-port': '50051',
        };
      case 'signet':
      default:
        return {
          'rpc-host': '127.0.0.1',
          'rpc-port': '6004',
          'net-addr': '0.0.0.0:4004',
          'zmq-addr': '127.0.0.1:28004',
          'mainchain-grpc-port': '50051',
        };
    }
  }

  @override
  String defaultConf(String network) {
    final ports = confPorts(network);

    return '''# BitAssets Configuration - Generated by BitAssets App
# These settings are converted to CLI arguments when BitAssets starts.

# Run in headless mode (no GUI)
headless=true

# Log level for console output
log-level=DEBUG

# Network (signet or regtest)
network=$network

# RPC server address
rpc-host=${ports['rpc-host']}
rpc-port=${ports['rpc-port']}

# P2P networking address
net-addr=${ports['net-addr']}

# ZMQ pub/sub address
zmq-addr=${ports['zmq-addr']}

# Mainchain (Enforcer) gRPC connection
mainchain-grpc-host=127.0.0.1
mainchain-grpc-port=${ports['mainchain-grpc-port']}
''';
  }

  @override
  List<String> get confSkippedCliKeys => const [];

  @override
  String confDir() => chain.rootDir();

  @override
  List<String> get defaultHomepageWidgets => [
    'quote_bar',
    'balance_card',
    'receive_card',
    'send_card',
    'bitassets_table',
  ];

  @override
  Map<String, HomepageWidgetInfo> get widgetCatalog => BitAssetsWidgetCatalog.getCatalogMap();

  @override
  String get homeTabLabel => 'Home';

  @override
  List<ShellTab> get tabs => const [
    ShellTab(
      label: 'BitAssets',
      route: BitAssetsTabRoute(),
      sourceFiles: ['reserve_register_page.dart', 'paymail_page.dart'],
    ),
    ShellTab(label: 'Messaging', route: BitAssetsMessagingRoute(), sourceFiles: ['messaging_view.dart']),
    ShellTab(label: 'Dutch Auction', route: DutchAuctionTabRoute(), sourceFiles: ['dutch_auction_page.dart']),
    ShellTab(label: 'AMM', route: AmmTabRoute(), sourceFiles: ['amm_page.dart']),
    ShellTab(label: 'Explorer', route: AssetExplorerTabRoute(), commandLabel: 'Asset Explorer'),
    ShellTab(label: 'Auctions', route: AuctionBrowserTabRoute(), commandLabel: 'Auction Browser'),
  ];

  @override
  List<AutoRoute> get tabRoutes => [
    AutoRoute(page: BitAssetsTabRoute.page),
    AutoRoute(page: BitAssetsMessagingRoute.page),
    AutoRoute(page: DutchAuctionTabRoute.page),
    AutoRoute(page: AmmTabRoute.page),
    AutoRoute(page: AssetExplorerTabRoute.page),
    AutoRoute(page: AuctionBrowserTabRoute.page),
  ];
}
