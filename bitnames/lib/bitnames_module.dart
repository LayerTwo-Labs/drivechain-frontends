import 'dart:io';

import 'package:auto_route/auto_route.dart';
import 'package:bitnames/gen/version.dart';
import 'package:bitnames/providers/bitnames_provider.dart';
import 'package:bitnames/routing/router.dart';
import 'package:bitnames/widgets/homepage_widget_catalog.dart';
import 'package:get_it/get_it.dart';
import 'package:logger/logger.dart';
import 'package:sail_ui/sail_ui.dart';
import 'package:sail_ui/shell/shell.dart';

class BitnamesModule extends SidechainModule {
  @override
  Sidechain get chain => BitNames();

  @override
  String get appName => 'BitNames';

  @override
  SidechainAppVersion get version => const SidechainAppVersion(
    version: AppVersion.version,
    versionString: AppVersion.versionString,
    buildDate: AppVersion.buildDate,
    commitFull: AppVersion.commitFull,
    appName: AppVersion.appName,
  );

  @override
  RootStackRouter registerRouter(GetIt getIt) {
    if (!getIt.isRegistered<AppRouter>()) {
      getIt.registerSingleton<AppRouter>(AppRouter());
    }
    return getIt.get<AppRouter>();
  }

  @override
  SidechainRPC registerRPC(GetIt getIt) {
    if (!getIt.isRegistered<BitnamesRPC>()) {
      getIt.registerSingleton<BitnamesRPC>(BitnamesLive());
    }
    return getIt.get<BitnamesRPC>();
  }

  @override
  Future<void> registerChainProviders(GetIt getIt, Directory applicationDir, Logger log) async {
    if (!getIt.isRegistered<BitnamesProvider>()) {
      getIt.registerLazySingleton<BitnamesProvider>(
        () => BitnamesProvider(),
        dispose: (provider) => provider.dispose(),
      );
    }
  }

  @override
  Map<String, String> confPorts(String network) {
    switch (network) {
      case 'regtest':
        return {
          'rpc-addr': '127.0.0.1:16002',
          'net-addr': '0.0.0.0:14002',
          'zmq-addr': '127.0.0.1:38002',
          'mainchain-grpc-port': '50051',
        };
      case 'mainnet':
        return {
          'rpc-addr': '127.0.0.1:26002',
          'net-addr': '0.0.0.0:24002',
          'zmq-addr': '127.0.0.1:48002',
          'mainchain-grpc-port': '50051',
        };
      case 'signet':
      default:
        return {
          'rpc-addr': '127.0.0.1:6002',
          'net-addr': '0.0.0.0:4002',
          'zmq-addr': '127.0.0.1:28002',
          'mainchain-grpc-port': '50051',
        };
    }
  }

  @override
  String defaultConf(String network) {
    final ports = confPorts(network);

    return '''# BitNames Configuration - Generated by BitNames App
# These settings are converted to CLI arguments when BitNames starts.

# Run in headless mode (no GUI)
headless=true

# Log level for console output
log-level=DEBUG

# Network (signet or regtest)
network=$network

# RPC server address
rpc-addr=${ports['rpc-addr']}

# P2P networking address
net-addr=${ports['net-addr']}

# ZMQ pub/sub address
zmq-addr=${ports['zmq-addr']}

# Mainchain (Enforcer) gRPC connection
mainchain-grpc-host=127.0.0.1
mainchain-grpc-port=${ports['mainchain-grpc-port']}
''';
  }

  @override
  List<String> get confSkippedCliKeys => const [];

  @override
  List<String> get defaultHomepageWidgets => [
    'quote_bar',
    'balance_card',
    'receive_card',
    'send_card',
    'bitnames_table',
  ];

  @override
  Map<String, HomepageWidgetInfo> get widgetCatalog => BitnamesWidgetCatalog.getCatalogMap();

  @override
  String get homeTabLabel => 'Home';

  @override
  List<ShellTab> get tabs => const [
    ShellTab(
      label: 'BitNames',
      route: BitnamesTabRoute(),
      sourceFiles: ['reserve_register_page.dart', 'paymail_page.dart'],
    ),
    ShellTab(label: 'Messaging', route: BitnamesMessagingRoute(), sourceFiles: ['messaging_view.dart']),
  ];

  @override
  List<AutoRoute> get tabRoutes => [
    AutoRoute(page: BitnamesTabRoute.page),
    AutoRoute(page: BitnamesMessagingRoute.page),
  ];
}
