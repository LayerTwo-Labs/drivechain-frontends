import 'dart:io';

import 'package:bitnames/bitnames_module.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:get_it/get_it.dart';
import 'package:logger/logger.dart';
import 'package:path/path.dart' as path;
import 'package:sail_ui/sail_ui.dart';
import 'package:sail_ui/shell/shell.dart';

const _oldDefaultConf = '''# BitNames Configuration - Generated by BitNames App
# These settings are converted to CLI arguments when BitNames starts.

# Run in headless mode (no GUI)
headless=true

# Log level for console output
log-level=DEBUG

# Network (signet or regtest)
network=signet

# RPC server address
rpc-addr=127.0.0.1:6002

# P2P networking address
net-addr=0.0.0.0:4002

# ZMQ pub/sub address
zmq-addr=127.0.0.1:28002

# Mainchain (Enforcer) gRPC connection
mainchain-grpc-host=127.0.0.1
mainchain-grpc-port=50051
''';

SidechainConfProvider _inDir(String dir, SidechainConfProvider source) => SidechainConfProvider(
  chain: source.chain,
  appName: source.appName,
  dataDir: () => dir,
  networkPorts: source.networkPorts,
  defaultConf: source.defaultConf,
  skippedCliKeys: source.skippedCliKeys,
);

void main() {
  late Directory dir;
  late SidechainConfProvider source;

  setUp(() async {
    GetIt.I.registerSingleton<Logger>(Logger(level: Level.off));
    source = sidechainConfProvider(BitnamesModule());
    dir = await Directory.systemTemp.createTemp('bitnames-conf-');
  });

  tearDown(() async {
    await GetIt.I.reset();
    await dir.delete(recursive: true);
  });

  test('the conf provider keeps the name and the default of bitnames.conf', () {
    expect(source.chain.registryKey, 'bitnames');
    expect(source.appName, 'BitNames');
    expect(source.configFileName, 'bitnames.conf');
    expect(source.skippedCliKeys, []);
    expect(source.getDefaultConfig(), _oldDefaultConf);
    expect(source.getNetworkPorts('regtest'), {
      'rpc-addr': '127.0.0.1:16002',
      'net-addr': '0.0.0.0:14002',
      'zmq-addr': '127.0.0.1:38002',
      'mainchain-grpc-port': '50051',
    });
    expect(source.getNetworkPorts('mainnet'), {
      'rpc-addr': '127.0.0.1:26002',
      'net-addr': '0.0.0.0:24002',
      'zmq-addr': '127.0.0.1:48002',
      'mainchain-grpc-port': '50051',
    });
  });

  test('the conf provider reads, writes and reads back a bitnames.conf of the old shape', () async {
    final file = File(path.join(dir.path, 'bitnames.conf'));
    await file.writeAsString(_oldDefaultConf.replaceFirst('net-addr=0.0.0.0:4002', 'net-addr=0.0.0.0:7777'));

    final provider = _inDir(dir.path, source);
    await provider.loadConfig();
    expect(provider.currentConfig!.getSetting('net-addr'), '0.0.0.0:7777');
    expect(provider.getCliArgs(), contains('--net-addr=0.0.0.0:7777'));

    final changed = provider.getCurrentConfigContent().replaceFirst('log-level=DEBUG', 'log-level=INFO');
    await provider.writeConfig(changed);
    expect(await file.readAsString(), changed);

    final reread = _inDir(dir.path, source);
    await reread.loadConfig();
    expect(reread.currentConfig!.getSetting('log-level'), 'INFO');
    expect(reread.currentConfig!.getSetting('net-addr'), '0.0.0.0:7777');
  });
}
